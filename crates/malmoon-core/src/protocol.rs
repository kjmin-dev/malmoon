//! Wire protocol between clients and the gateway.
//!
//! Control messages and captions travel as JSON text frames over one WebSocket. Audio travels as
//! binary frames on the same socket and has no JSON envelope.

use serde::{Deserialize, Serialize};

/// Bumped on any change that an older peer cannot ignore.
pub const PROTOCOL_VERSION: u16 = 1;

/// Path of the session WebSocket on the gateway.
pub const SESSION_PATH: &str = "/v1/session";

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
#[serde(rename_all = "snake_case")]
pub enum ClientKind {
    Desktop,
    Web,
    Mobile,
}

/// Which audio stream a caption came from. The two streams are captured separately, so the
/// channel also tells the user's own speech apart from everyone else's.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
#[serde(rename_all = "snake_case")]
pub enum Channel {
    /// The user's microphone.
    Mic,
    /// System audio: the other participants.
    System,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
#[serde(rename_all = "snake_case")]
pub enum CaptionStage {
    /// Still being recognized. Later updates with the same `segment_id` replace it.
    Draft,
    /// Recognition is settled. A later final update may still refine the translation.
    Final,
}

/// One caption segment in its latest known state.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
pub struct CaptionUpdate {
    /// Identifies the segment within a session. Ids increase in speaking order.
    #[cfg_attr(feature = "ts", ts(type = "number"))]
    pub segment_id: u64,
    pub channel: Channel,
    pub stage: CaptionStage,
    /// What was said, in the language it was said in.
    pub original: String,
    /// Translation into the user's language, once one exists.
    pub translation: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum ClientMessage {
    /// Must be the first message on a new connection.
    Hello {
        protocol_version: u16,
        client: ClientKind,
    },
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
#[serde(rename_all = "snake_case")]
pub enum ErrorCode {
    /// The first message was not a valid `hello`.
    ExpectedHello,
    /// The client speaks a protocol version this gateway does not support.
    UnsupportedProtocol,
    /// A text frame was not a valid client message.
    InvalidMessage,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum ServerMessage {
    /// Answers `hello`. The session is open from here on.
    Ready {
        protocol_version: u16,
        session_id: String,
    },
    Caption {
        caption: CaptionUpdate,
    },
    /// The gateway closes the connection after sending this.
    Error {
        code: ErrorCode,
        message: String,
    },
}

/// Writes the protocol constants next to the TypeScript bindings that ts-rs exports, so the
/// TypeScript clients cannot drift from the values above. Run by `mise run //:protocol`.
#[cfg(all(test, feature = "ts"))]
#[test]
fn export_constants() {
    let dir = std::env::var("TS_RS_EXPORT_DIR").unwrap_or_else(|_| "bindings".to_owned());
    let source = format!(
        "// This file was generated by malmoon-core. Do not edit this file manually.\n\n\
         export const PROTOCOL_VERSION = {PROTOCOL_VERSION};\n\n\
         export const SESSION_PATH = {SESSION_PATH:?};\n"
    );
    std::fs::create_dir_all(&dir).unwrap();
    std::fs::write(std::path::Path::new(&dir).join("constants.ts"), source).unwrap();
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn hello_uses_a_type_tag_and_snake_case() {
        let hello = ClientMessage::Hello {
            protocol_version: PROTOCOL_VERSION,
            client: ClientKind::Desktop,
        };
        assert_eq!(
            serde_json::to_string(&hello).unwrap(),
            r#"{"type":"hello","protocol_version":1,"client":"desktop"}"#
        );
    }

    #[test]
    fn caption_round_trips() {
        let message = ServerMessage::Caption {
            caption: CaptionUpdate {
                segment_id: 7,
                channel: Channel::System,
                stage: CaptionStage::Draft,
                original: "Let's ship it".into(),
                translation: Some("출시합시다".into()),
            },
        };
        let json = serde_json::to_string(&message).unwrap();
        assert!(json.starts_with(r#"{"type":"caption","caption":{"segment_id":7,"#));
        assert_eq!(
            serde_json::from_str::<ServerMessage>(&json).unwrap(),
            message
        );
    }

    #[test]
    fn unknown_message_types_are_rejected() {
        assert!(serde_json::from_str::<ClientMessage>(r#"{"type":"nope"}"#).is_err());
    }
}
